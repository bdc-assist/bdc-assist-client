import { describe, expect, it, vi } from 'vitest'

import { drawnGraph, studyList } from '@/kg'
import { asthmaCopd, related } from '@/kg/test-fixtures'
import {
  BLOCKED_PART,
  FOLLOWUPS_PART,
  GRAPH_PART,
  SOURCES_PART,
  STATUS_PART,
  UNAVAILABLE_PART,
  type GraphPartData,
} from '@/lib/bdc-adapter'
import {
  graphCount,
  graphsOf,
  graphSummary,
  toEmail,
  turnsOf,
  type AnswerPart,
  type EmailMessage,
  type EmailOptions,
  type EmailTurn,
} from '@/lib/email-export'

const text = (t: string): AnswerPart => ({ type: 'text', text: t })
const data = (name: string, d: unknown = {}): AnswerPart => ({ type: 'data', name, data: d })
const graphPart = data(GRAPH_PART, { graph: asthmaCopd, parts: [] } satisfies GraphPartData)

const DATE = new Date(2026, 9, 30)
const options = (over: Partial<EmailOptions> = {}): EmailOptions => ({ title: 'Asthma studies', date: DATE, graphs: true, ...over })
const turn = (question: string, ...answer: AnswerPart[]): EmailTurn => ({ question, answer })

describe('toEmail', () => {
  it('titles it, and dates it in the footer', () => {
    const email = toEmail([turn('Hi?', text('Hello.'))], options())
    expect(email.subject).toBe('BDC Assist: Asthma studies')
    expect(email.html).toContain('BDC Assist · Asthma studies')
    expect(email.html).toContain('Generated by BDC Assist on')
    expect(email.html).toContain('2026')
    expect(email.text.split('\n').at(-1)).toMatch(/^Generated by BDC Assist on .*2026\.$/)
  })

  it('says just BDC Assist without a title', () => {
    expect(toEmail([turn('Hi?', text('Hello.'))], options({ title: '' })).subject).toBe('BDC Assist')
  })

  it('sets no text, background or link colours: the mail client picks them (dark mode)', () => {
    const { html } = toEmail([turn('Hi?', text('See [BDC](https://biodatacatalyst.nhlbi.nih.gov/).'))], options())
    expect(html).not.toMatch(/background/)
    // the only colour set is the mid grey of labels, notes and borders
    expect(html.match(/color:[^;"]+/g)?.every((c) => c.includes('#8a8a8a'))).toBe(true)
    expect(html).toMatch(/<a href="https:\/\/biodatacatalyst\.nhlbi\.nih\.gov\/">BDC<\/a>/)
  })

  it('labels each question and escapes it', () => {
    const { html } = toEmail([turn('Is <b> bold?', text('No.'))], options())
    expect(html).toContain('>Question</span>Is &lt;b&gt; bold?')
  })

  it('renders the answer markdown with inline styles', () => {
    const md = '## Studies\n\n- **CARDIA**\n- MESA\n\n| a | b |\n|---|---|\n| 1 | 2 |\n\n`code`'
    const { html } = toEmail([turn('Which?', text(md))], options())
    expect(html).toMatch(/<p style="[^"]*font-weight:bold[^"]*">Studies<\/p>/) // headings: bold paragraphs
    expect(html).toMatch(/<ul style="[^"]*">\s*<li><strong>CARDIA<\/strong><\/li>/)
    expect(html).toMatch(/<td style="[^"]*border:1px solid #8a8a8a[^"]*">1<\/td>/) // GFM tables
    expect(html).toMatch(/<code style="[^"]*monospace[^"]*">code<\/code>/)
    expect(html).not.toContain('node=')
  })

  it('leaves out status, sources and follow-ups', () => {
    const answer = [
      text('Answer.'),
      data(STATUS_PART, { node: 'agent', status: null }),
      data(SOURCES_PART, { 'bdc-doc': [{ title: 'Secret doc', link: 'https://example.org/doc', type: 'docs' }] }),
      data(FOLLOWUPS_PART, ['What next?']),
    ]
    const email = toEmail([turn('Q?', ...answer)], options())
    for (const out of [email.html, email.text]) {
      expect(out).not.toContain('Secret doc')
      expect(out).not.toContain('example.org')
      expect(out).not.toContain('What next?')
      expect(out).not.toContain('Thinking')
    }
  })

  it('notes a stopped, failed, blocked or degraded answer', () => {
    const email = toEmail(
      [
        { question: 'A?', answer: [text('Half')], ended: 'stopped' },
        { question: 'B?', answer: [text('')], ended: 'failed' },
        turn('C?', text('Sorry.'), data(BLOCKED_PART)),
        turn('D?', text('Partial.'), data(UNAVAILABLE_PART, ['dug'])),
      ],
      options(),
    )
    for (const note of [
      'Answer stopped',
      'Answer failed',
      'Outside what BDC Assist can help with',
      'Some data services were unavailable',
    ]) {
      expect(email.html).toContain(`(${note}`)
      expect(email.text).toContain(`(${note}`)
    }
    expect(email.html).not.toContain('dug') // server names are for whoever runs it
  })

  it('without graphs, says one was there', () => {
    const graph = vi.fn()
    const { html, text: plain } = toEmail([turn('Q?', text('A.'), graphPart)], options({ graphs: false, graph }))
    expect(graph).not.toHaveBeenCalled()
    expect(html).toContain(`A knowledge graph of ${graphSummary(asthmaCopd)} was shown here in BDC Assist.`)
    expect(html).not.toContain('<img')
    expect(plain).toContain(`[Knowledge graph: ${graphSummary(asthmaCopd)}]`)
  })

  it('puts in a graph image, at most 640 wide, with its view in the caption', () => {
    const src = 'data:image/png;base64,AAAA'
    const { html } = toEmail(
      [turn('Q?', text('A.'), graphPart)],
      options({ graph: () => ({ image: { src, width: 1280, height: 800 }, view: 'force' }) }),
    )
    expect(html).toContain(`<img src="${src}" width="640" height="400" alt="Knowledge graph: ${graphSummary(asthmaCopd)}"`)
    expect(html).toContain(`Knowledge graph (Force view): ${graphSummary(asthmaCopd)}`)
  })

  it("puts in a List view's graph as a table of its studies", () => {
    const { html } = toEmail([turn('Q?', text('A.'), graphPart)], options({ graph: () => ({ table: true }) }))
    const studies = studyList(drawnGraph(asthmaCopd))
    expect(html.match(/<tr>/g)).toHaveLength(studies.length + 1) // + the header row
    expect(html).toContain(studies[0].study!.id)
  })

  it('asks for each graph in order through the turns', () => {
    const graph = vi.fn((_data: GraphPartData, _index: number) => null)
    toEmail([turn('A?', graphPart), turn('B?', text('none')), turn('C?', graphPart)], options({ graph }))
    expect(graph.mock.calls.map(([, index]) => index)).toEqual([0, 1])
  })

  it('reads graphs saved before per-call graphs (just the graph)', () => {
    const { html } = toEmail([turn('Q?', data(GRAPH_PART, asthmaCopd))], options({ graphs: false }))
    expect(html).toContain(graphSummary(asthmaCopd))
  })

  it('keeps the markdown as it is in the plain text', () => {
    const { text: plain } = toEmail([turn('Which?', text('- **CARDIA**\n- MESA'))], options())
    expect(plain).toContain('Question: Which?\n\n- **CARDIA**\n- MESA\n')
  })
})

describe('turnsOf', () => {
  const user = (id: string, t: string): EmailMessage => ({ id, role: 'user', content: [text(t)] })
  const bot = (id: string, t: string, status?: EmailMessage['status']): EmailMessage => ({
    id,
    role: 'assistant',
    content: [text(t)],
    ...(status && { status }),
  })
  const messages = [
    user('u1', 'First?'),
    bot('a1', 'One.'),
    user('u2', 'Second?'),
    bot('a2', 'Half', { type: 'incomplete', reason: 'cancelled' }),
    user('u3', 'Third?'),
    bot('a3', '', { type: 'incomplete', reason: 'error' }),
  ]

  it('pairs every answer with the question before it', () => {
    expect(turnsOf(messages, 'full', 'a1').map((t) => [t.question, textOfTurn(t)])).toEqual([
      ['First?', 'One.'],
      ['Second?', 'Half'],
      ['Third?', ''],
    ])
  })

  it('takes only the answer asked for', () => {
    expect(turnsOf(messages, 'single', 'a2').map((t) => t.question)).toEqual(['Second?'])
  })

  it('marks stopped and failed answers', () => {
    expect(turnsOf(messages, 'full', 'a1').map((t) => t.ended)).toEqual([undefined, 'stopped', 'failed'])
  })

  it('lists the graphs, by the answer graph objects the panels are keyed by', () => {
    const old = data(GRAPH_PART, related) // saved before per-call graphs: just the graph
    expect(graphsOf([turn('A?', graphPart), turn('B?', old)])).toEqual([asthmaCopd, related])
    expect(graphsOf([turn('A?', graphPart)])[0]).toBe(asthmaCopd)
  })

  it('counts the graphs', () => {
    const turns = [turn('A?', graphPart), turn('B?', text('none')), turn('C?', graphPart)]
    expect(graphCount(turns)).toBe(2)
    expect(graphCount(turns.slice(1, 2))).toBe(0)
  })
})

const textOfTurn = (t: EmailTurn) => t.answer.map((p) => p.text).join('')

describe('graphSummary', () => {
  it('counts studies and variables as drawn, and names what was asked about', () => {
    const drawn = drawnGraph(asthmaCopd)
    const n = (type: string) => drawn.nodes.filter((x) => x.type === type).length
    const asked = drawn.nodes.filter((x) => x.seed).map((x) => x.label)
    expect(asked.length).toBeGreaterThan(0)
    expect(graphSummary(asthmaCopd)).toBe(`${n('study')} studies, ${n('variable')} variables (${asked.join(', ')})`)
  })
})
